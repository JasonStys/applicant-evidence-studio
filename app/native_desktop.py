from __future__ import annotations

import os
import sys
import tkinter as tk
from pathlib import Path
from tkinter import messagebox

from app.native_host import LocalService, OwnerWindow
from app.native_identity import bounded_bytes, verify_bundle, verify_gui
from app.native_profile import DesktopOwnership, external_directory
from app.private_api import create_private_app


def private_directory() -> Path:
    """Select the existing per-user account path without reading or creating account records."""
    if os.environ.get("AES_DESKTOP_DATA"):
        return Path(os.environ["AES_DESKTOP_DATA"])
    if sys.platform == "win32":
        parent = Path(os.environ.get("LOCALAPPDATA", Path.home() / "AppData/Local"))
    elif sys.platform == "darwin":
        parent = Path.home() / "Library/Application Support"
    else:
        parent = Path(os.environ.get("XDG_DATA_HOME", Path.home() / ".local/share"))
    return parent / "ApplicantEvidenceStudio"


def main() -> int:
    """Retain ownership through shutdown, including a window/service startup exception."""
    bundle = Path(getattr(sys, "_MEIPASS", Path(__file__).resolve().parents[1]))
    forbidden = (Path(sys.executable).resolve().parent, bundle) if getattr(sys, "frozen", False) else ()
    ui = bundle / "dist"
    if not (ui / "index.html").is_file():
        raise SystemExit("Application UI missing. Use a complete release or build the UI first.")
    nonce = os.environ.get("AES_ACCEPTANCE_NONCE")
    if nonce and (not os.environ.get("AES_DESKTOP_DATA") or os.environ.get("AES_NO_BROWSER") != "1"):
        raise SystemExit(
            "Explicit acceptance requires a selected synthetic profile and no automatic browser."
        )
    root = None
    try:
        metadata = verify_bundle(bundle)
        root = tk.Tk()
        root.withdraw()
        verify_gui(root.tk, metadata)
        notices = (
            bounded_bytes(bundle / "NATIVE_NOTICES.txt", 4 * 1024 * 1024).decode("utf-8")
            if getattr(sys, "frozen", False)
            else "Development source checkout. Packaged downloads include the actual Python, Tcl/Tk and dependency notices."
        )
        selected = external_directory(private_directory(), forbidden)
        with DesktopOwnership(selected, forbidden):

            def application_factory(directory: Path, origin: str, assets: Path):
                """Bind verified public frozen identity; source-server mode keeps its original health contract."""
                return create_private_app(
                    directory,
                    origin,
                    assets,
                    native_identity=metadata if getattr(sys, "frozen", False) else None,
                )

            service = LocalService(application_factory, selected, ui)
            try:
                window = OwnerWindow(
                    root, service, open_browser=os.environ.get("AES_NO_BROWSER") != "1", notices=notices
                )
                if nonce:
                    window.acceptance_input(nonce)
                service.thread.start()
                root.deiconify()
                root.mainloop()
            finally:
                # This is INSIDE ownership: exceptional UI setup/closure must
                # also drain before another process can acquire the profile.
                service.close()
            return 2 if service.failed else 0
    except (OSError, ValueError, tk.TclError):
        if root is not None and os.environ.get("AES_NO_BROWSER") != "1":
            messagebox.showerror(
                "Applicant Evidence Studio",
                "This private profile is unavailable or already open. Existing accounts were not reset.",
                parent=root,
            )
        return 2
    finally:
        if root is not None:
            try:
                root.destroy()
            except tk.TclError:
                pass
