// Purpose: Jason Stys — build-time JSON schema validators, avoiding runtime eval under strict CSP.
// Index: fs@3, Ajv@4, standalone@5, prettier@6, ajv@7, output@15, helpers@16, _@17, name@17, header@23, name@25
import fs from 'node:fs';
import Ajv from 'ajv/dist/2020.js';
import standalone from 'ajv/dist/standalone/index.js';
import prettier from 'prettier';
const ajv = new Ajv({
  strict: false,
  useDefaults: true,
  allErrors: false,
  code: { source: true, esm: true },
});
ajv.addSchema(JSON.parse(fs.readFileSync('examples/applicant-batch.schema.json', 'utf8')), 'batch');
ajv.addSchema(JSON.parse(fs.readFileSync('examples/job.schema.json', 'utf8')), 'job');
let output = standalone(ajv, { validBatch: 'batch', validJob: 'job' });
const helpers = new Set();
output = output.replace(/require\("ajv\/dist\/runtime\/(\w+)"\)\.default/g, (_, name) => {
  helpers.add(name);
  return 'helper_' + name;
});
if (output.includes('require('))
  throw new Error('Unexpected schema runtime helper: inspect before publishing.');
const header =
  '// Jason Stys: generated schema validators. Functions/variables are generated by Ajv; do not edit.\n// Source and lexical locations: examples/*.schema.json and scripts/compile_schemas.mjs; browser code contains no eval.\n';
if ([...helpers].some((name) => name !== 'ucs2length'))
  throw new Error('Inspect new schema helper before publishing.');
output =
  header +
  'function helper_ucs2length(value) { let length=0; for (const character of value) { void character; length++; } return length; }\n' +
  output +
  '\n';
output = await prettier.format(output, {
  parser: 'babel',
  singleQuote: true,
  trailingComma: 'all',
  printWidth: 110,
});
if (process.argv.includes('--check')) {
  if (fs.readFileSync('web/validators.generated.js', 'utf8') !== output)
    throw new Error('Generated validators are stale. Run npm run schemas.');
} else fs.writeFileSync('web/validators.generated.js', output);
